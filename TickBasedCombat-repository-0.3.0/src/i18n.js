export function getLanguage() {
  const settings = globalThis.game?.settings;
  if (settings?.settings && !settings.settings.has("tick-combat.language")) return "en";
  return settings?.get?.("tick-combat", "language") === "de" ? "de" : "en";
}

export function strings() {
  return messages[getLanguage()];
}

export function t(key, values = {}) {
  return strings()[key].replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}
